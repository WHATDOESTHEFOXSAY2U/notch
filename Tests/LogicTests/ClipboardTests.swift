import AppKit
import Testing
@testable import Logic

// Clipboard.swift, on a pasteboard of its own for each test, gone after it: the real clipboard is never touched.
// One test at a time, because Clipboard remembers the hidden text it put out last, by the change count alone.
@MainActor @Suite(.serialized) struct ClipboardTests {
    let board = NSPasteboard(name: NSPasteboard.Name("notch.tests.\(UUID().uuidString)"))
    let marks = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                 "de.petermaurer.TransientPasteboardType"]

    /// Plain text makes Clipboard forget the hidden text of the test before, which was on another pasteboard.
    init() { Clipboard.put("", incognito: false, on: board) }

    /// Someone copies `text`, the way any app does.
    func copy(_ text: String) {
        board.clearContents()
        board.setString(text, forType: .string)
    }

    @Test func plainTextIsSimplyThere() {
        defer { board.releaseGlobally() }
        let count = Clipboard.put("hello", incognito: false, on: board)
        #expect(count == board.changeCount)
        #expect(board.string(forType: .string) == "hello")
        #expect(!(board.types ?? []).contains { marks.contains($0.rawValue) })
    }

    @Test func incognitoTextIsMarkedAndHandedOverOnlyWhenAsked() {
        defer { board.releaseGlobally() }
        var taken = 0
        Clipboard.put("secret words", incognito: true, on: board) { taken += 1 }
        #expect(Set(marks).isSubset(of: (board.types ?? []).map(\.rawValue)))
        #expect(taken == 0)   // nothing handed over yet
        #expect(board.string(forType: .string) == "secret words")   // a paste asks for it...
        #expect(taken == 1)   // ...and `taken` runs
        _ = board.string(forType: .string)
        #expect(taken == 1)   // the first time only
    }

    @Test func incognitoTextIsNeverSavedForLater() {
        defer { board.releaseGlobally() }
        copy("before")
        Clipboard.put("secret words", incognito: true, before: Clipboard.save(board), on: board)
        #expect(Clipboard.save(board).map { $0.string(forType: .string) } == ["before"])   // what it replaced
    }

    @Test func saveKeepsEveryKindOfData() {
        defer { board.releaseGlobally() }
        let item = NSPasteboardItem()
        item.setString("plain", forType: .string)
        item.setString("<b>bold</b>", forType: .html)
        board.clearContents()
        board.writeObjects([item])
        let saved = Clipboard.save(board)
        #expect(saved.count == 1)
        #expect(saved.first?.string(forType: .string) == "plain")
        #expect(saved.first?.string(forType: .html) == "<b>bold</b>")
    }

    @Test func restorePutsBackWhatWasThere() async throws {
        defer { board.releaseGlobally() }
        copy("before")
        let saved = Clipboard.save(board)
        let count = Clipboard.put("secret words", incognito: true, before: saved, on: board)
        Clipboard.restore(saved, after: 0.05, unlessChangedSince: count, on: board)
        #expect(board.string(forType: .string) == "secret words")   // not yet
        try await Task.sleep(for: .milliseconds(300))
        #expect(board.string(forType: .string) == "before")
    }

    @Test func restoreLeavesWhatYouCopiedMeanwhile() async throws {
        defer { board.releaseGlobally() }
        copy("before")
        let saved = Clipboard.save(board)
        let count = Clipboard.put("dictated", incognito: false, before: saved, on: board)
        copy("yours")
        Clipboard.restore(saved, after: 0.05, unlessChangedSince: count, on: board)
        try await Task.sleep(for: .milliseconds(300))
        #expect(board.string(forType: .string) == "yours")
    }

    @Test func restoreOfAnEmptyClipboardEmptiesIt() async throws {
        defer { board.releaseGlobally() }
        board.clearContents()
        let saved = Clipboard.save(board)
        let count = Clipboard.put("dictated", incognito: false, before: saved, on: board)
        Clipboard.restore(saved, after: 0.05, unlessChangedSince: count, on: board)
        try await Task.sleep(for: .milliseconds(300))
        #expect(board.pasteboardItems?.isEmpty ?? true)
    }
}
